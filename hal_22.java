public class hal_22 {
    public static void main(String[] args) {
  
        System.out.println("\n--- Operator Aritmatika Java ---");

        int hasilTambah = 456 + 97;
        System.out.println("456 + 97 = " + hasilTambah);

        double hasilKurang = 100 - 11;
        System.out.println("100 - 11 = " + hasilKurang);

        float hasilDesimal = (float) (14.32 - 4.95);
        System.out.println("14.32 - 4.95 = " + hasilDesimal);

        double hasilBagi = 826 / 3; 
        System.out.println("826 / 3 = " + hasilBagi);

        int hasilModulus = 76 % 13;
        System.out.println("76 % 13 = " + hasilModulus);
    }
}
